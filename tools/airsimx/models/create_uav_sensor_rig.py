"""Create/update a derived Pawn with generated, non-colliding visual components.

The original script depended on private FlyingPawn properties. This adapter uses
the public UE editor subobject API; it does not alter AirSim C++ or sensor APIs.
"""

import argparse
import importlib
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _model_workflow import (DEFAULT_ASSETS, DEFAULT_CONFIG, DEFAULT_OUTPUT,
                              DEFAULT_PARENT, DEFAULT_RIG, rig_plan, write_report, select_scene_root)

METADATA_TAG = 'AirsimX.ProceduralSensorRig.v1'


def run_create(plan):
    unreal = importlib.import_module('unreal')
    library = unreal.EditorAssetLibrary
    base = unreal.load_asset(plan['parent_blueprint'])
    if base is None or not isinstance(base, unreal.Blueprint):
        raise RuntimeError(f'parent Blueprint not found: {plan["parent_blueprint"]}')
    parent_class = unreal.BlueprintEditorLibrary.generated_class(base)
    if parent_class is None:
        raise RuntimeError('parent Blueprint has no generated class')
    parent_root = unreal.get_default_object(parent_class).get_editor_property('root_component')
    meshes = {}
    for entry in plan['components']:
        mesh = unreal.load_asset(entry['asset'])
        if mesh is None or not isinstance(mesh, unreal.StaticMesh):
            raise RuntimeError(f'import the configured visual StaticMesh first: {entry["asset"]}')
        meshes[entry['name']] = mesh
    exists = library.does_asset_exist(plan['blueprint_asset'])
    previous = None
    if exists:
        if not plan['replace_existing']:
            raise RuntimeError('target Blueprint exists; choose a new path or pass --replace-existing')
        bp = unreal.load_asset(plan['blueprint_asset'])
        marker = library.get_metadata_tag(bp, METADATA_TAG)
        if not isinstance(bp, unreal.Blueprint) or not marker:
            raise RuntimeError('refusing to update a Blueprint not marked as generated by this script')
        previous = json.loads(marker)
        if bp.get_editor_property('parent_class') != parent_class:
            raise RuntimeError('the generated Blueprint was reparented; choose a new output path')
        if (previous['parent'] != plan['parent_blueprint']
                or set(previous['components']) != {p['name'] for p in plan['components']}):
            raise RuntimeError('parent/component names changed; choose a new Blueprint path')
    else:
        bp = unreal.BlueprintEditorLibrary.create_blueprint_asset_with_parent(
            plan['blueprint_asset'], parent_class)
    if bp is None:
        raise RuntimeError('could not create or load the derived Blueprint')
    subsystem = unreal.get_engine_subsystem(unreal.SubobjectDataSubsystem)
    bfl = unreal.SubobjectDataBlueprintFunctionLibrary
    handles = subsystem.k2_gather_subobject_data_for_blueprint(bp)
    if not handles:
        raise RuntimeError('Blueprint has no subobject context')
    objects = {}
    scene_components = []
    for handle in handles:
        data = bfl.get_data(handle)
        obj = bfl.get_object_for_blueprint(data, bp)
        if obj is not None:
            objects[str(bfl.get_variable_name(data))] = obj
            if isinstance(obj, unreal.SceneComponent):
                scene_components.append({'variable_name': str(bfl.get_variable_name(data)),
                                         'object_name': obj.get_name(), 'handle': handle,
                                         'is_scene_component': True,
                                         'is_root_component': bfl.is_root_component(data)})
    root = select_scene_root(scene_components, parent_root.get_name() if parent_root is not None else None)
    generated_names = {}
    for entry in plan['components']:
        name = entry['name']
        if previous is not None:
            component = objects.get(previous['components'][name])
            if component is None or not isinstance(component, unreal.StaticMeshComponent):
                raise RuntimeError(f'generated component is missing or has changed type: {name}')
        else:
            handle, reason = subsystem.add_new_subobject(unreal.AddNewSubobjectParams(
                parent_handle=root['handle'], new_class=unreal.StaticMeshComponent, blueprint_context=bp))
            if not reason.is_empty():
                raise RuntimeError(f'could not add {name}: {reason}')
            if not subsystem.rename_subobject(handle, unreal.Text(name)):
                raise RuntimeError(f'could not name component {name}')
            component = bfl.get_object_for_blueprint(bfl.get_data(handle), bp)
            if component is None or not isinstance(component, unreal.StaticMeshComponent):
                raise RuntimeError(f'could not resolve the new StaticMeshComponent {name}')
        component.set_static_mesh(meshes[name])
        component.set_editor_property('mobility', unreal.ComponentMobility.MOVABLE)
        component.set_collision_enabled(unreal.CollisionEnabled.NO_COLLISION)
        component.set_editor_property('generate_overlap_events', False)
        component.set_editor_property('relative_location', unreal.Vector(*entry['location_cm']))
        roll, pitch, yaw = entry['rotation_rpy_deg']
        component.set_editor_property('relative_rotation', unreal.Rotator(pitch=pitch, yaw=yaw, roll=roll))
        component.set_editor_property('relative_scale3d', unreal.Vector(*entry['scale']))
        generated_names[name] = name
    unreal.BlueprintEditorLibrary.compile_blueprint(bp)
    generated = unreal.BlueprintEditorLibrary.generated_class(bp)
    if generated is None:
        raise RuntimeError('derived Blueprint has no generated class after compilation')
    library.set_metadata_tag(bp, METADATA_TAG, json.dumps(
        {'parent': plan['parent_blueprint'], 'components': generated_names}, sort_keys=True))
    if not library.save_loaded_asset(bp, only_if_is_dirty=False):
        raise RuntimeError('could not save the derived Blueprint')
    return {**plan, 'status': 'sensor_rig_blueprint_saved', 'engine_executed': True,
            'engine_version': unreal.SystemLibrary.get_engine_version(),
            'generated_class': generated.get_path_name(), 'reused_existing': exists,
            'component_variable_names': generated_names,
            'evidence_boundary': 'saved visual components only; no flight, physics calibration or sensor configuration'}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--config', type=Path, default=DEFAULT_CONFIG)
    parser.add_argument('--asset-root', default=DEFAULT_ASSETS)
    parser.add_argument('--blueprint-asset', default=DEFAULT_RIG)
    parser.add_argument('--parent-blueprint', default=DEFAULT_PARENT)
    parser.add_argument('--report', type=Path, default=DEFAULT_OUTPUT / 'sensor_rig_blueprint.json')
    parser.add_argument('--replace-existing', action='store_true')
    parser.add_argument('--dry-run', action='store_true')
    args = parser.parse_args(argv)
    plan = rig_plan(args.config, args.asset_root, args.blueprint_asset,
                    args.parent_blueprint, args.replace_existing)
    report = plan if args.dry_run else run_create(plan)
    write_report(args.report, report)
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == '__main__':
    main()
