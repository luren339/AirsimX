#!/usr/bin/env bash
# Start the pinned PX4 external-MAVLink SITL build. Software simulation only.
# Usage: start_sitl.sh <run-id>
# Environment: AIRSIMX_PX4_ROOT (default /opt/airsimx), PX4_SIM_HOST_ADDR (default 127.0.0.1).
set -euo pipefail

run_id="${1:?Provide a new run identifier}"
if [[ ! "$run_id" =~ ^[A-Za-z0-9_-]+$ ]]; then
    printf '%s\n' 'Invalid run identifier.' >&2
    exit 2
fi
root="${AIRSIMX_PX4_ROOT:-/opt/airsimx}"
# AIRSIMX_PX4_BUILD selects the build directory when a variant was built
# beside the default one (the DDS-enabled board is px4_sitl_dds). The board
# label may not start with an existing label: PX4 resolves the label by
# substring match, so "airsimdds" silently selects the "airsim" board.
build="$root/src/PX4-Autopilot-v1.17.0/build/${AIRSIMX_PX4_BUILD:-px4_sitl_airsim}"
run="$root/runs/$run_id"
[[ -x "$build/bin/px4" && -f "$build/etc/init.d-posix/rcS" ]] || {
    printf '%s\n' "PX4 build not found at $build; run build_sitl.sh first." >&2
    exit 2
}
mkdir -p "$root/runs"
[[ ! -e "$run" ]] || { printf '%s\n' "Run directory already exists: $run" >&2; exit 2; }
mkdir "$run"
printf '%s\n' 'Simulation-only run. No hardware or serial connections.' > "$run/SITL_ONLY"
printf '%s\n' "$$" > "$run/px4.pid"

# HIL transport: TCP by default (AirSim listens, PX4 connects). With
# AIRSIMX_HIL=udp PX4 binds a UDP port and learns the simulator peer from the
# first HIL_SENSOR packet, so the simulator host never needs an inbound port.
if [[ "${AIRSIMX_HIL:-tcp}" == "udp" ]]; then
    rc="$build/etc/init.d-posix/px4-rc.mavlinksim"
    [[ -f "$rc.orig" ]] || cp "$rc" "$rc.orig"
    port="${AIRSIMX_HIL_UDP_PORT:-14560}"
    cat > "$rc" <<EOF
#!/bin/sh
# AirsimX: external-simulator HIL over UDP (generated by start_sitl.sh).
simulator_mavlink start -u $port
EOF
    printf '%s\n' "HIL transport: UDP port $port (PX4 learns the simulator peer from the first sensor packet)"
fi
[[ "${AIRSIMX_HIL:-tcp}" == "tcp" && -f "$build/etc/init.d-posix/px4-rc.mavlinksim.orig" ]] && \
    cp "$build/etc/init.d-posix/px4-rc.mavlinksim.orig" "$build/etc/init.d-posix/px4-rc.mavlinksim"
export PX4_SIM_HOST_ADDR="${PX4_SIM_HOST_ADDR:-127.0.0.1}"
export PX4_SIM_MODEL=none_iris
export PX4_SYS_AUTOSTART=10016
export PX4_SIM_SPEED_FACTOR="${PX4_SIM_SPEED_FACTOR:-1}"
# PX4 instance N shifts every MAVLink port by N (px4-rc.mavlink: offboard
# 14580+N -> 14540+N, GCS 18570+N, ...). Use a non-zero instance when another
# tool on the host holds instance 0's ports (for example a MAVLink guard that
# reserves 14540/14550); the AirSim profile must then use the matching
# ControlPortLocal/ControlPortRemote.
instance="${AIRSIMX_PX4_INSTANCE:-0}"
printf '%s\n' "PX4 SITL run: $run (host $PX4_SIM_HOST_ADDR, instance $instance)"

# Optional parameters applied at boot. MAVLink parameter writes from the
# simulator arrive after boot, but some parameters (EKF2_HGT_REF) are
# documented as reboot_required and are only read when their module
# initialises. PX4's rcS already reads ``PX4_PARAM_<NAME>`` environment
# variables and applies them with ``param set`` before starting modules, so
# the values simply go into the environment; no script rewriting is needed.
# Format: AIRSIMX_PX4_PARAMS="EKF2_HGT_REF=0;SIM_BAT_DRAIN=43200"
if [[ -n "${AIRSIMX_PX4_PARAMS:-}" ]]; then
    IFS=';' read -ra assignments <<< "$AIRSIMX_PX4_PARAMS"
    for assignment in "${assignments[@]}"; do
        [[ -n "$assignment" ]] || continue
        name="${assignment%%=*}"
        value="${assignment#*=}"
        export "PX4_PARAM_${name}=${value}"
    done
    printf 'Boot parameters: %s\n' "$AIRSIMX_PX4_PARAMS"
fi

exec > >(tee "$run/console.log") 2>&1
# PX4 applies the PX4_PARAM_* environment overrides from its own rcS.
exec "$build/bin/px4" -d "$build/etc" -w "$run" -i "$instance" -s etc/init.d-posix/rcS
